def sh(txt, dx=0, dy=0):
    out = []
    for l in txt.strip().splitlines():
        if not l.strip():
            continue
        y, resto = l.split(":", 1)
        x0, t = resto.strip().split(" ", 1) if " " in resto.strip() else (resto.strip(), "")
        out.append(f"{int(y) + dy}: {int(x0) + dx} {t}")
    return "\n" + "\n".join(out) + "\n"


