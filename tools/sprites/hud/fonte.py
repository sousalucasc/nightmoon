def _acento(base, tipo, maiuscula):
    topo, linhas = G[base]
    w = max(len(l) for l in linhas)
    marcas = {"agudo": ["...#", "..#."], "grave": ["#...", ".#.."], "circ": [".#.", "#.#"],
              "til": [".#.#", "#.#."]}[tipo]
    mw = len(marcas[0])
    off = max(0, (w - mw) // 2 + (1 if tipo == "agudo" and w > 4 else 0))
    marcas = ["." * off + m for m in marcas]
    if maiuscula:
        return (0, marcas + linhas)
    return (2, marcas + linhas)


