def quadro(ch):
    corpo = P.RAMPAS["texto"][2]
    sombra = P.RAMPAS["texto"][0]
    im = Image.new("RGBA", (8, 12), (0, 0, 0, 0))
    if ch == " ":
        im.putpixel((0, 8), (0, 0, 0, 1))
        im.putpixel((2, 8), (0, 0, 0, 1))
        return im
    topo, linhas = G[ch]
    pts = {(x, topo + y) for y, l in enumerate(linhas) for x, c in enumerate(l) if c == "#"}
    for (x, y) in pts:
        if (x + 1, y + 1) not in pts and x + 1 < 8 and y + 1 < 12:
            im.putpixel((x + 1, y + 1), tuple(sombra) + (255,))
    for (x, y) in pts:
        im.putpixel((x, y), tuple(corpo) + (255,))
    return im


def quadros():
    return [quadro(c) for c in ORDEM]


def escrever(texto, cor=None, sep=1):
    """Prévia: escreve com a fonte como o GameMaker (proporcional, sep 1)."""
    import numpy as np
    ims = []
    for c in texto:
        q = quadro(c if c in ORDEM else "?")
        a = np.array(q)
        xs = np.nonzero(a[:, :, 3] > 0)[1]
        w = (xs.max() + 1) if len(xs) else 3
        ims.append((q, w))
    W = sum(w + sep for _, w in ims)
    out = Image.new("RGBA", (max(1, W), 12), (0, 0, 0, 0))
    x = 0
    for q, w in ims:
        if cor is not None:
            a = np.array(q).astype(int)
            m = a[:, :, 3] == 255
            for k in range(3):
                a[:, :, k] = np.where(m, a[:, :, k] * cor[k] // 255, a[:, :, k])
            q = Image.fromarray(a.astype("uint8"), "RGBA")
        out.alpha_composite(q.crop((0, 0, w, 12)), (x, 0))
        x += w + sep
    return out


