def quadro(texto, leg, paleta):
    primeira = texto.strip().splitlines()[0]
    if primeira.split(":")[0].strip().isdigit():
        return de_segmentos(texto, leg, paleta, 32, 32)
    return de_texto(texto, leg, paleta, w=32, h=32)


